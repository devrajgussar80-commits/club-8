@router.get("/api/admin/visitors/summary")
def visitors_summary(hours: int = 24, _: bool = Depends(require_admin)):
    """The funnel: landed -> saw the auth screen -> tried -> converted."""
    hours = max(1, min(hours, 24 * 90))
    window = f"{hours} hours"

    conn = get_db_connection()
    try:
        row = conn.execute(
            """
            SELECT COUNT(*) AS sessions,
                   COUNT(DISTINCT visitor_id) AS visitors,
                   COUNT(*) FILTER (WHERE outcome = 'registered') AS registered,
                   COUNT(*) FILTER (WHERE outcome = 'logged_in') AS logged_in,
                   COUNT(*) FILTER (WHERE outcome = 'browsing') AS still_anonymous,
                   COUNT(*) FILTER (WHERE page_views <= 1 AND active_seconds < 10) AS bounced,
                   COALESCE(ROUND(AVG(active_seconds)), 0) AS avg_seconds,
                   COALESCE(ROUND(AVG(active_seconds) FILTER (WHERE outcome = 'browsing')), 0)
                       AS avg_seconds_anonymous
            FROM visitor_sessions
            WHERE started_at >= NOW() - ?::interval
            """,
            (window,),
        ).fetchone()

        funnel = conn.execute(
            """
            SELECT COUNT(DISTINCT session_id) FILTER (WHERE name = 'auth_view') AS saw_auth,
                   COUNT(DISTINCT session_id) FILTER (WHERE name = 'field_focus') AS started_typing,
                   COUNT(DISTINCT session_id) FILTER (WHERE name = 'register_submit') AS tried_register,
                   COUNT(DISTINCT session_id) FILTER (WHERE name = 'login_submit') AS tried_login,
                   COUNT(DISTINCT session_id) FILTER (WHERE name IN ('register_failed','login_failed'))
                       AS had_failure
            FROM visitor_events
            WHERE created_at >= NOW() - ?::interval
            """,
            (window,),
        ).fetchone()

        devices = conn.execute(
            """
            SELECT device, browser, COUNT(*) AS sessions
            FROM visitor_sessions
            WHERE started_at >= NOW() - ?::interval
            GROUP BY device, browser ORDER BY sessions DESC LIMIT 10
            """,
            (window,),
        ).fetchall()
    finally:
        conn.close()

    landed = int(row["sessions"] or 0)
    converted = int(row["registered"] or 0) + int(row["logged_in"] or 0)
    return {
        "hours": hours,
        "visitors": int(row["visitors"] or 0),
        "sessions": landed,
        "registered": int(row["registered"] or 0),
        "logged_in": int(row["logged_in"] or 0),
        "still_anonymous": int(row["still_anonymous"] or 0),
        "bounced": int(row["bounced"] or 0),
        "avg_seconds": int(row["avg_seconds"] or 0),
        "avg_seconds_anonymous": int(row["avg_seconds_anonymous"] or 0),
        # Undefined with no traffic -- None rather than a flattering 0%.
        "conversion_rate": round(converted / landed * 100, 1) if landed else None,
        "funnel": {
            "landed": landed,
            "saw_auth": int(funnel["saw_auth"] or 0),
            "started_typing": int(funnel["started_typing"] or 0),
            "tried_register": int(funnel["tried_register"] or 0),
            "tried_login": int(funnel["tried_login"] or 0),
            "had_failure": int(funnel["had_failure"] or 0),
            "converted": converted,
        },
        "devices": [dict(entry) for entry in devices],
    }


@router.get("/api/admin/visitors")
def visitors(
    hours: int = 24,
    outcome: Optional[str] = None,
    limit: int = 100,
    _: bool = Depends(require_admin),
):
    hours = max(1, min(hours, 24 * 90))
    limit = max(1, min(limit, 500))
    params = [f"{hours} hours"]
    clause = ""
    # The outcome filter is interpolated only after being matched against this
    # fixed set, so nothing from the query string reaches the SQL text.
    if outcome in ("browsing", "registered", "logged_in"):
        clause = "AND s.outcome = ?"
        params.append(outcome)
    params.append(limit)

    conn = get_db_connection()
    try:
        rows = conn.execute(
            f"""
            SELECT s.*, u.username, u.phone
            FROM visitor_sessions s
            LEFT JOIN users u ON u.id = s.user_id
            WHERE s.started_at >= NOW() - ?::interval
              {clause}
            ORDER BY s.last_seen_at DESC
            LIMIT ?
            """,
            params,
        ).fetchall()
    finally:
        conn.close()

    return {
        "sessions": [
            {
                **dict(row),
                "started_at": str(row["started_at"]),
                "last_seen_at": str(row["last_seen_at"]),
            }
            for row in rows
        ]
    }


@router.get("/api/admin/visitors/daily")
def visitors_daily(days: int = 60, _: bool = Depends(require_admin)):
    """Visitor sessions grouped into one bucket per calendar day.

    Declared before the /{session_id} route so "daily" is never mistaken for a
    session id. Each day carries that day's sessions plus its own totals.
    """
    days = max(1, min(days, 365))
    conn = get_db_connection()
    try:
        rows = conn.execute(
            """
            SELECT s.id, s.visitor_id, s.ip, s.device, s.browser, s.os,
                   s.landing_path, s.last_path, s.page_views, s.active_seconds,
                   s.outcome, s.started_at, s.user_id, u.username, u.phone
            FROM visitor_sessions s
            LEFT JOIN users u ON u.id = s.user_id
            WHERE s.started_at >= NOW() - ?::interval
            ORDER BY s.started_at DESC
            """,
            (f"{days} days",),
        ).fetchall()
    finally:
        conn.close()

    days_map = {}
    for row in rows:
        started = row["started_at"]
        key = started.date().isoformat()
        bucket = days_map.setdefault(
            key,
            {
                "date": key,
                "label": started.strftime("%A, %d %B %Y"),
                "sessions": 0,
                "visitors": set(),
                "registered": 0,
                "logged_in": 0,
                "anonymous": 0,
                "bounced": 0,
                "seconds_total": 0,
                "rows": [],
            },
        )
        seconds = int(row["active_seconds"] or 0)
        bucket["sessions"] += 1
        bucket["visitors"].add(row["visitor_id"])
        bucket["seconds_total"] += seconds
        outcome = row["outcome"] or "browsing"
        if outcome == "registered":
            bucket["registered"] += 1
        elif outcome == "logged_in":
            bucket["logged_in"] += 1
        else:
            bucket["anonymous"] += 1
        if int(row["page_views"] or 0) <= 1 and seconds < 10:
            bucket["bounced"] += 1
        bucket["rows"].append(
            {
                "id": row["id"],
                "time": started.strftime("%H:%M"),
                "visitor": row["username"] or (row["visitor_id"][:10] + "…"),
                "phone": row["phone"],
                "ip": row["ip"],
                "device": f'{row["device"] or "?"} · {row["browser"] or "?"}',
                "journey": f'{row["landing_path"] or "?"} → {row["last_path"] or "?"}',
                "seconds": seconds,
                "outcome": outcome,
            }
        )

    result = []
    for day in sorted(days_map.values(), key=lambda d: d["date"], reverse=True):
        count = day["sessions"]
        result.append(
            {
                "date": day["date"],
                "label": day["label"],
                "sessions": count,
                "visitors": len(day["visitors"]),
                "registered": day["registered"],
                "logged_in": day["logged_in"],
                "anonymous": day["anonymous"],
                "bounced": day["bounced"],
                "avg_seconds": round(day["seconds_total"] / count) if count else 0,
                "rows": day["rows"],
            }
        )
    return {"days": result}


@router.get("/api/admin/visitors/{session_id}")
def visitor_timeline(session_id: str, _: bool = Depends(require_admin)):
    """Everything one visit did, in order -- the 'kis page tak aaya' view."""
    conn = get_db_connection()
    try:
        session = conn.execute(
            """
            SELECT s.*, u.username, u.phone
            FROM visitor_sessions s
            LEFT JOIN users u ON u.id = s.user_id
            WHERE s.id = ?
            """,
            (session_id,),
        ).fetchone()
        if not session:
            raise HTTPException(status_code=404, detail="Session not found.")
        events = conn.execute(
            """
            SELECT name, path, meta, created_at FROM visitor_events
            WHERE session_id = ? ORDER BY created_at, id
            """,
            (session_id,),
        ).fetchall()
        # Other visits from the same browser, so a returning stranger reads as
        # one person rather than a row per visit.
        other = conn.execute(
            """
            SELECT id, started_at, outcome, active_seconds, page_views
            FROM visitor_sessions
            WHERE visitor_id = ? AND id <> ?
            ORDER BY started_at DESC LIMIT 20
            """,
            (session["visitor_id"], session_id),
        ).fetchall()
    finally:
        conn.close()

    return {
        "session": {
            **dict(session),
            "started_at": str(session["started_at"]),
            "last_seen_at": str(session["last_seen_at"]),
        },
        "events": [
            {**dict(event), "created_at": str(event["created_at"])} for event in events
        ],
        "other_visits": [
            {**dict(visit), "started_at": str(visit["started_at"])} for visit in other
        ],
    }
